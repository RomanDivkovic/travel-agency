using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;
using TravelAgency.Domain.Admin;
using TravelAgency.Domain.Bookings;
using TravelAgency.Domain.Customers;
using TravelAgency.Domain.Documents;
using TravelAgency.Domain.Messaging;
using TravelAgency.Domain.Payments;
using TravelAgency.Domain.Quotations;
using TravelAgency.Domain.Requests;
using TravelAgency.Domain.Research;
using TravelAgency.Infrastructure.Admin;
using TravelAgency.Infrastructure.Bookings;
using TravelAgency.Infrastructure.Customers;
using TravelAgency.Infrastructure.Documents;
using TravelAgency.Infrastructure.Messaging;
using TravelAgency.Infrastructure.Payments;
using TravelAgency.Infrastructure.Quotations;
using TravelAgency.Infrastructure.Requests;
using TravelAgency.Infrastructure.Research;

namespace TravelAgency.Infrastructure.Persistence;

public sealed class TravelAgencyDbContext(DbContextOptions<TravelAgencyDbContext> options) : IdentityDbContext<Administrator>(options)
{
    public DbSet<CustomerConversation> Conversations => Set<CustomerConversation>();
    public DbSet<ConversationMessage> ConversationMessages => Set<ConversationMessage>();
    public DbSet<ConversationReadState> ConversationReads => Set<ConversationReadState>();
    public DbSet<ConversationEvent> ConversationEvents => Set<ConversationEvent>();
    public DbSet<TravelDocument> TravelDocuments => Set<TravelDocument>();
    public DbSet<TravelDocumentVersion> DocumentVersions => Set<TravelDocumentVersion>();
    public DbSet<DocumentBlob> DocumentBlobs => Set<DocumentBlob>();
    public DbSet<ItinerarySeries> Itineraries => Set<ItinerarySeries>();
    public DbSet<TravelItinerary> ItineraryVersions => Set<TravelItinerary>();
    public DbSet<CustomerRequestOwnership> CustomerRequests => Set<CustomerRequestOwnership>();
    public DbSet<CustomerAccountAction> CustomerActions => Set<CustomerAccountAction>();
    public DbSet<CustomerSecurityEvent> CustomerSecurityEvents => Set<CustomerSecurityEvent>();
    public DbSet<TravelBooking> Bookings => Set<TravelBooking>();
    public DbSet<SupplierReservation> SupplierReservations => Set<SupplierReservation>();
    public DbSet<BookingEvent> BookingEvents => Set<BookingEvent>();
    public DbSet<ResearchWorkspace> ResearchWorkspaces => Set<ResearchWorkspace>();
    public DbSet<ResearchOption> ResearchOptions => Set<ResearchOption>();
    public DbSet<ProposalSeries> ProposalSeries => Set<ProposalSeries>();
    public DbSet<TravelProposal> TravelProposals => Set<TravelProposal>();
    public DbSet<ProposalItem> ProposalItems => Set<ProposalItem>();
    public DbSet<ProposalAccessToken> ProposalTokens => Set<ProposalAccessToken>();
    public DbSet<ProposalDecision> ProposalDecisions => Set<ProposalDecision>();
    public DbSet<Invoice> Invoices => Set<Invoice>();
    public DbSet<PaymentTransaction> Payments => Set<PaymentTransaction>();
    public DbSet<PaymentEventRecord> PaymentEvents => Set<PaymentEventRecord>();
    public DbSet<InvoiceAccessToken> InvoiceTokens => Set<InvoiceAccessToken>();
    public DbSet<ResearchEligibility> ResearchEligibility => Set<ResearchEligibility>();
    public DbSet<InvoiceCounter> InvoiceCounters => Set<InvoiceCounter>();
    public DbSet<SandboxPayment> SandboxPayments => Set<SandboxPayment>();
    public DbSet<TravelInquiry> TravelRequests => Set<TravelInquiry>();
    public DbSet<IdempotencyRecord> IdempotencyRecords => Set<IdempotencyRecord>();
    public DbSet<NotificationRecord> NotificationOutbox => Set<NotificationRecord>();
    public DbSet<RequestNote> RequestNotes => Set<RequestNote>();
    public DbSet<RequestActivity> RequestActivities => Set<RequestActivity>();
    public DbSet<QuotationSeries> QuotationSeries => Set<QuotationSeries>();
    public DbSet<Quotation> Quotations => Set<Quotation>();
    public DbSet<QuotationAccessToken> QuotationTokens => Set<QuotationAccessToken>();
    protected override void OnModelCreating(ModelBuilder model)
    {
        base.OnModelCreating(model);
        model.ConfigureQuotations();
        model.ConfigurePayments();
        model.ConfigureResearch();
        model.ConfigureBookings();
        model.ConfigureCustomers();
        model.ConfigureDocuments();
        model.ConfigureMessaging();
        model.Entity<Administrator>().Property(a => a.DisplayName).HasMaxLength(100);
        var note = model.Entity<RequestNote>();
        note.HasKey(n => n.Id);
        note.Property(n => n.Content).HasMaxLength(4000).IsRequired();
        note.HasIndex(n => new { n.RequestId, n.CreatedAt, n.Id });
        note.HasOne<TravelInquiry>().WithMany().HasForeignKey(n => n.RequestId).OnDelete(DeleteBehavior.Cascade);
        note.HasOne<Administrator>().WithMany().HasForeignKey(n => n.AdministratorId).OnDelete(DeleteBehavior.Restrict);
        var activity = model.Entity<RequestActivity>();
        activity.HasKey(a => a.Id);
        activity.HasOne<TravelBooking>().WithMany().HasForeignKey(a => a.BookingId).OnDelete(DeleteBehavior.Cascade);
        activity.HasOne<TravelProposal>().WithMany().HasForeignKey(a => a.ProposalId).OnDelete(DeleteBehavior.Cascade);
        activity.HasOne<Quotation>().WithMany().HasForeignKey(a => a.QuotationId).OnDelete(DeleteBehavior.Cascade);
        activity.Property(a => a.Type).HasMaxLength(20).IsRequired();
        activity.Property(a => a.PreviousValue).HasMaxLength(24);
        activity.Property(a => a.NewValue).HasMaxLength(24);
        activity.HasIndex(a => new { a.RequestId, a.CreatedAt, a.Id });
        activity.HasOne<TravelInquiry>().WithMany().HasForeignKey(a => a.RequestId).OnDelete(DeleteBehavior.Cascade);
        activity.HasOne<Administrator>().WithMany().HasForeignKey(a => a.ActorId).OnDelete(DeleteBehavior.Restrict);
        model.HasSequence<long>("travel_request_reference");
        var request = model.Entity<TravelInquiry>();
        request.HasKey(r => r.Id);
        request.Property(r => r.Version).IsConcurrencyToken();
        request.HasIndex(r => r.UpdatedAt);
        request.HasIndex(r => new { r.Service, r.CreatedAt });
        request.Property(r => r.ReferenceNumber).HasMaxLength(40).IsRequired();
        request.HasIndex(r => r.ReferenceNumber).IsUnique();
        request.Property(r => r.Service).HasConversion<string>().HasMaxLength(32);
        request.Property(r => r.Status).HasConversion<string>().HasMaxLength(24);
        request.Property(r => r.Language).HasMaxLength(2).IsRequired();
        request.HasIndex(r => r.CreatedAt);
        request.HasIndex(r => new { r.Status, r.CreatedAt });
        request.OwnsOne(r => r.Contact, contact =>
        {
            contact.Property(c => c.Name).HasMaxLength(100).IsRequired();
            contact.Property(c => c.Email).HasMaxLength(254).IsRequired();
            contact.Property(c => c.Phone).HasMaxLength(40);
            contact.Property(c => c.PreferredMethod).HasMaxLength(8).IsRequired();
        });
        request.Navigation(r => r.Contact).IsRequired();
        request.OwnsOne(r => r.Plan, plan =>
        {
            plan.Property(p => p.Origin).HasMaxLength(150);
            plan.Property(p => p.Destination).HasMaxLength(150);
            plan.Property(p => p.DateMode).HasMaxLength(8).IsRequired();
            plan.Property(p => p.BudgetAmount).HasPrecision(12, 2);
            plan.Property(p => p.Currency).HasMaxLength(3).IsRequired();
            plan.Property(p => p.BudgetScope).HasMaxLength(16).IsRequired();
            plan.Property(p => p.SpecialRequests).HasMaxLength(2000);
            plan.Property(p => p.PreferencesJson).HasColumnType("jsonb").IsRequired();
        });
        request.Navigation(r => r.Plan).IsRequired();
        request.ToTable(t =>
        {
            t.HasCheckConstraint("CK_Request_Budget", "\"Plan_BudgetAmount\" > 0 AND \"Plan_BudgetAmount\" <= 100000000");
            t.HasCheckConstraint("CK_Request_Travelers", "\"Plan_Adults\" BETWEEN 1 AND 20 AND cardinality(\"Plan_ChildrenAges\") <= 10 AND \"Plan_Adults\" + cardinality(\"Plan_ChildrenAges\") <= 20");
            t.HasCheckConstraint("CK_Request_Status", "\"Status\" IN ('Submitted', 'UnderReview', 'AwaitingCustomer', 'Closed')");
        });
        var key = model.Entity<IdempotencyRecord>();
        key.HasKey(k => k.KeyHash);
        key.Property(k => k.KeyHash).HasMaxLength(64);
        key.Property(k => k.PayloadHash).HasMaxLength(64).IsRequired();
        key.HasIndex(k => k.ExpiresAt);
        key.HasOne<TravelInquiry>().WithMany().HasForeignKey(k => k.RequestId).OnDelete(DeleteBehavior.Cascade);
        var notification = model.Entity<NotificationRecord>();
        notification.HasKey(n => n.Id);
        notification.HasOne<Administrator>().WithMany().HasForeignKey(n => n.CustomerId).OnDelete(DeleteBehavior.Cascade);
        notification.HasOne<CustomerAccountAction>().WithMany().HasForeignKey(n => n.CustomerActionId).OnDelete(DeleteBehavior.Cascade);
        notification.HasIndex(n => n.CustomerActionId);
        notification.HasOne<TravelBooking>().WithMany().HasForeignKey(n => n.BookingId).OnDelete(DeleteBehavior.Cascade);
        notification.Property(n => n.PayloadJson).HasColumnType("jsonb");
        notification.HasIndex(n => new { n.BookingId, n.Kind }).IsUnique().HasFilter("\"BookingId\" IS NOT NULL");
        notification.HasIndex(n => new { n.ProposalId, n.Kind }).IsUnique().HasFilter("\"ProposalId\" IS NOT NULL");
        notification.HasOne<TravelProposal>().WithMany().HasForeignKey(n => n.ProposalId).OnDelete(DeleteBehavior.Cascade);
        notification.HasIndex(n => new { n.InvoiceId, n.Kind }).IsUnique().HasFilter("\"InvoiceId\" IS NOT NULL");
        notification.HasOne<Invoice>().WithMany().HasForeignKey(n => n.InvoiceId).OnDelete(DeleteBehavior.Cascade);
        notification.Property(n => n.Kind).HasMaxLength(64).IsRequired();
        notification.HasIndex(n => new { n.RequestId, n.Kind }).IsUnique().HasFilter("\"QuotationId\" IS NULL AND \"InvoiceId\" IS NULL AND \"ProposalId\" IS NULL AND \"BookingId\" IS NULL");
        notification.HasIndex(n => new { n.QuotationId, n.Kind }).IsUnique().HasFilter("\"QuotationId\" IS NOT NULL");
        notification.HasOne<Quotation>().WithMany().HasForeignKey(n => n.QuotationId).OnDelete(DeleteBehavior.Cascade);
        notification.HasIndex(n => n.NextAttemptAt).HasFilter("\"SentAt\" IS NULL AND \"DeadLetterAt\" IS NULL");
        notification.HasOne<TravelInquiry>().WithMany().HasForeignKey(n => n.RequestId).OnDelete(DeleteBehavior.Cascade);
    }
}
