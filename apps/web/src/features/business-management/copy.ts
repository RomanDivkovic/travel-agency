export function fieldLabel(key: string, sv: boolean) {
  return key
    .replace(/^(shared|public)\./, '')
    .split('.')
    .map(
      (p) =>
        labels[p]?.[sv ? 0 : 1] ||
        (/^\d+$/.test(p)
          ? String(Number(p) + 1)
          : p.replace(/([A-Z])/g, ' $1')),
    )
    .join(' · ');
}
